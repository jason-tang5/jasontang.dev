const image = bits => Float32Array.from({ length: 784 }, (_, i) => (parseInt(bits.slice(Math.floor(i / 28) * 7, Math.floor(i / 28) * 7 + 7), 16) >> (27 - i % 28)) & 1);

test('the weights read every digit in fig 1', () => {
  for (const [label, bits] of digits) {
    const probs = guessDigit(net, image(bits));
    assert.equal(probs.indexOf(Math.max(...probs)), label);
    assert.ok(Math.abs(probs.reduce((a, b) => a + b, 0) - 1) < 1e-5);
  }
});

test('a drawing is cropped, shrunk to 20 pixels and centred like mnist', () => {
  assert.equal(toMnist(new Uint8ClampedArray(100 * 100), 100), null);
  // a bar 10 wide and 60 tall in the top left corner of a 100 × 100 drawing
  const gray = new Uint8ClampedArray(100 * 100);
  for (let y = 5; y < 65; y++) for (let x = 2; x < 12; x++) gray[y * 100 + x] = 255;
  const out = toMnist(gray, 100);
  const lit = [...out.keys()].filter(i => out[i] > 0.5);
  const rows = new Set(lit.map(i => Math.floor(i / 28))), cols = new Set(lit.map(i => i % 28));
  assert.equal(rows.size, 20);
  assert.ok(Math.min(...rows) >= 3 && Math.max(...rows) <= 24);
  assert.ok(Math.min(...cols) >= 12 && Math.max(...cols) <= 15);
});
